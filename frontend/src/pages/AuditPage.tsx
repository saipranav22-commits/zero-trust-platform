import { useState } from 'react';
import { useQuery } from '@tanstack/react-query';
import { Search, CheckCircle, XCircle, FileText, Loader2, Shield, AlertTriangle } from 'lucide-react';
import { Layout } from '@/components/layout/Layout';
import { PageHeader } from '@/components/ui/PageHeader';
import { AuditStatusBadge, RiskScoreBadge } from '@/components/ui/Badge';
import { Pagination, EmptyState } from '@/components/ui/Shared';
import { auditApi } from '@/api/threat.api';
import { formatDistanceToNow, format } from 'date-fns';
import toast from 'react-hot-toast';
import type { AuditLog } from '@/types';

export function AuditPage() {
  const [page, setPage] = useState(0);
  const [search, setSearch] = useState('');
  const [actionFilter, setActionFilter] = useState('');
  const [statusFilter, setStatusFilter] = useState('');
  const [verifying, setVerifying] = useState<string | null>(null);
  const [verifyResults, setVerifyResults] = useState<Record<string, { valid: boolean; message: string }>>({});

  const filters = {
    userId: search,
    action: actionFilter,
    status: statusFilter,
  };

  const { data, isLoading, refetch } = useQuery({
    queryKey: ['audit-logs', page, filters],
    queryFn: () => auditApi.getLogs({ ...filters, page, size: 20 }),
  });

  const verifyLog = async (id: string) => {
    setVerifying(id);
    try {
      const result = await auditApi.verifyIntegrity(id);
      setVerifyResults((prev) => ({ ...prev, [id]: { valid: result.integrityValid, message: result.message } }));
      if (result.integrityValid) {
        toast.success('Log integrity verified — untampered');
      } else {
        toast.error('INTEGRITY FAILURE — log may have been tampered!');
      }
    } catch {
      toast.error('Failed to verify log integrity');
    } finally {
      setVerifying(null);
    }
  };

  const handleExport = () => {
    if (!data?.content || data.content.length === 0) {
      toast.error('No audit logs available to export');
      return;
    }

    const headers = [
      'ID',
      'Action',
      'User Email',
      'Status',
      'Risk Score',
      'Source IP',
      'Details',
      'Hash',
      'Created At'
    ];

    const rows = data.content.map((log) => [
      log.id,
      log.action,
      log.userEmail ?? '',
      log.status,
      String(log.riskScore),
      log.sourceIp ?? '',
      log.details ?? '',
      log.currentHash ?? '',
      log.createdAt
    ]);

    const metadata = [
      '# SYVORA',
      '# AI-Powered Zero Trust Security Platform',
      '# Audit Log Explorer Integrity Report',
      '# Confidential',
      '# Generated by Syvora AI',
      `# Generated At: ${new Date().toISOString()}`,
      ''
    ].join('\n');

    const csvContent = metadata + [
      headers.join(','),
      ...rows.map(row => row.map(val => `"${val.replace(/"/g, '""')}"`).join(','))
    ].join('\n');

    const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.setAttribute('href', url);
    link.setAttribute('download', `syvora_audit_report_${Date.now()}.csv`);
    link.style.visibility = 'hidden';
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    toast.success('Audit log explorer report exported successfully');
  };

  const TABLE_HEADERS = ['Action', 'User', 'Status', 'Risk Score', 'Source IP', 'Details', 'Hash', 'Time', 'Verify'];

  return (
    <Layout onRefresh={refetch} isRefreshing={isLoading}>
      <PageHeader
        title="Audit Explorer"
        description="Immutable, cryptographically hash-chained audit trail logging all actions"
        icon={<Shield className="w-5 h-5" />}
        onRefresh={refetch}
        isRefreshing={isLoading}
        onExport={handleExport}
      />

      {/* ─── Toolbar ──────────────────────────────── */}
      <div className="sentinel-toolbar">
        <div className="relative max-w-xs flex-1 min-w-[200px]">
          <Search className="absolute left-3 top-1/2 -translate-y-1/2 w-3.5 h-3.5 text-[#64748B]" />
          <input
            type="text"
            placeholder="Search by user ID…"
            value={search}
            onChange={(e) => {
              setSearch(e.target.value);
              setPage(0);
            }}
            className="sentinel-input pl-9"
          />
        </div>

        <div className="relative min-w-[180px]">
          <Search className="absolute left-3 top-1/2 -translate-y-1/2 w-3.5 h-3.5 text-[#64748B]" />
          <input
            type="text"
            placeholder="Filter by action…"
            value={actionFilter}
            onChange={(e) => {
              setActionFilter(e.target.value);
              setPage(0);
            }}
            className="sentinel-input pl-9"
          />
        </div>

        <select
          className="sentinel-input w-auto min-w-[140px]"
          value={statusFilter}
          onChange={(e) => {
            setStatusFilter(e.target.value);
            setPage(0);
          }}
        >
          <option value="">All Statuses</option>
          <option value="SUCCESS">SUCCESS</option>
          <option value="FAILURE">FAILURE</option>
          <option value="BLOCKED">BLOCKED</option>
        </select>

        {(search || actionFilter || statusFilter) && (
          <button
            onClick={() => {
              setSearch('');
              setActionFilter('');
              setStatusFilter('');
              setPage(0);
            }}
            className="sentinel-btn-ghost text-xs py-1.5"
          >
            Clear Filters
          </button>
        )}

        <div className="ml-auto">
          <span className="text-xs text-[#64748B] font-medium">
            {data?.totalElements ?? 0} events logged
          </span>
        </div>
      </div>

      {/* ─── Table ────────────────────────────────── */}
      <div className="sentinel-card overflow-hidden">
        <div className="overflow-x-auto">
          <table className="sentinel-table">
            <thead className="sentinel-thead">
              <tr>
                {TABLE_HEADERS.map((h) => (
                  <th key={h} className="sentinel-th">
                    {h}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody>
              {isLoading && Array.from({ length: 8 }).map((_, i) => (
                <tr key={i}>
                  {Array.from({ length: 9 }).map((_, j) => (
                    <td key={j} className="sentinel-td">
                      <div className="skeleton h-4 rounded w-16" />
                    </td>
                  ))}
                </tr>
              ))}
              {!isLoading && !data?.content?.length && (
                <tr>
                  <td colSpan={9}>
                    <EmptyState
                      message="No Audit Logs Found"
                      description="Immutable records will appear as actions are performed on the platform."
                      icon={<FileText className="w-6 h-6" />}
                    />
                  </td>
                </tr>
              )}
              {data?.content?.map((log: AuditLog) => (
                <tr key={log.id} className="sentinel-tr">
                  <td className="sentinel-td">
                    <span className="font-mono text-xs text-[#F8FAFC] bg-[#1F2530] px-2 py-0.5 rounded border border-[#2D3642]">
                      {log.action}
                    </span>
                  </td>
                  <td className="sentinel-td">
                    <div>
                      <p className="text-xs text-[#F8FAFC] font-semibold">{log.userEmail ?? '—'}</p>
                      <p className="text-[10px] text-[#64748B] font-mono mt-0.5">{log.userId?.slice(0, 8)}…</p>
                    </div>
                  </td>
                  <td className="sentinel-td"><AuditStatusBadge status={log.status} /></td>
                  <td className="sentinel-td"><RiskScoreBadge score={log.riskScore} /></td>
                  <td className="sentinel-td font-mono text-xs text-[#94A3B8]">{log.sourceIp ?? '—'}</td>
                  <td className="sentinel-td">
                    <span className="text-xs text-[#94A3B8] max-w-[140px] truncate block" title={log.details ?? ''}>
                      {log.details ?? '—'}
                    </span>
                  </td>
                  <td className="sentinel-td">
                    <span className="font-mono text-xs text-[#64748B] max-w-[100px] truncate block" title={log.currentHash ?? ''}>
                      {log.currentHash ? `${log.currentHash.slice(0, 12)}…` : '—'}
                    </span>
                  </td>
                  <td className="sentinel-td text-xs text-[#64748B] whitespace-nowrap font-medium">
                    {format(new Date(log.createdAt), 'MM/dd HH:mm:ss')}
                  </td>
                  <td className="sentinel-td">
                    <div className="flex items-center gap-2">
                      {verifyResults[log.id] ? (
                        verifyResults[log.id].valid ? (
                          <CheckCircle className="w-4 h-4 text-[#16A34A] animate-fade-in" />
                        ) : (
                          <XCircle className="w-4 h-4 text-[#DC2626] animate-fade-in" />
                        )
                      ) : (
                        <button
                          onClick={() => verifyLog(log.id)}
                          disabled={verifying === log.id}
                          title="Verify hash integrity"
                          className="p-1.5 rounded-lg text-[#64748B] hover:text-[#16A34A] hover:bg-[#16A34A]/10 transition-colors disabled:opacity-40"
                        >
                          {verifying === log.id ? (
                            <Loader2 className="w-3.5 h-3.5 animate-spin" />
                          ) : (
                            <CheckCircle className="w-3.5 h-3.5" />
                          )}
                        </button>
                      )}
                    </div>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>

        {data && data.totalPages > 1 && (
          <Pagination
            page={data.page}
            totalPages={data.totalPages}
            totalElements={data.totalElements}
            size={data.size}
            onPageChange={setPage}
          />
        )}
      </div>
    </Layout>
  );
}
